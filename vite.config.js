// vite.config.ts
import { defineConfig, build } from 'vite';
import { resolve } from 'path';
import { dts } from 'rolldown-plugin-dts';

const iifeBuild = () => ({
  name: 'iife-build',
  closeBundle: async () => {
    await build({
      configFile: false,
      build: {
        lib: {
          entry: resolve(__dirname, 'src/js/index.iife.ts'),
          name: 'PanelSet',
          formats: ['iife'],
          fileName: () => 'panelset.js'
        },
        emptyOutDir: false,
        sourcemap: false,
        minify: 'terser',
        terserOptions: {
          // Smaller bundle.
          mangle: { properties: { regex: /^_/ } },
          compress: { passes: 3 }
        },
        target: 'es2020'
      }
    });
  }
});



export default defineConfig({
  // rolldown-plugin-dts: keep generated declarations away from Oxc (and JS, as Vite does by default)
  oxc: { exclude: [/\.js$/, /\.d\.[cm]?ts$/] },
  plugins: [
    // Bundled types per entry, next to the modules: dist/panelset.d.mts and register.d.mts.
    // Generated by tsc and bundled by rolldown.
    dts({ tsconfig: 'tsconfig.json' }),
    iifeBuild()
  ],
  build: {
    // One ES module per entry: dist/panelset.mjs and dist/register.mjs, which
    // imports panelset.mjs. No source maps in the package.
    lib: {
      entry: {
        'index': resolve(__dirname, 'src/js/index.ts'),
        'register': resolve(__dirname, 'src/js/register.ts'),
      },
      formats: ['es'],
    },
    rollupOptions: {
      // The code both entries use stays in panelset.mjs, not in a third file.
      preserveEntrySignatures: 'allow-extension',
      output: {
        // Declaration entries are named 'index.d' and 'register.d'
        entryFileNames: (chunk) => {
          const name = chunk.name.replace(/\.d$/, '') === 'index' ? 'panelset' : chunk.name.replace(/\.d$/, '');
          return chunk.name.endsWith('.d') ? `${name}.d.mts` : `${name}.mjs`;
        },
        chunkFileNames: (chunk) => (chunk.name.endsWith('.d') ? '[name].mts' : '[name].mjs'),
        assetFileNames: '[name][extname]',
      }
    },
    sourcemap: false,
    minify: 'oxc',
    target: 'es2020'
  },
  server: {
    host: true,
    open: "index.html",
}
});